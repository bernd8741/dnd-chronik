$("#export-entries").addEventListener("click", () => {
  if (!entries.length) { toast("Du hast noch keine eigenen Einträge geschrieben."); return; }
  const blob = new Blob([JSON.stringify({ version: 1, entries }, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = make("a");
  link.href = url;
  link.download = "unsere-chronik.json";
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});
