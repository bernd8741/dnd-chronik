const storageKey = "dnd-chronik-v1";
let storageWarning = false;
let stored = {};
try {
  const parsed = JSON.parse(localStorage.getItem(storageKey) || "{}");
  if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) stored = parsed;
} catch { storageWarning = true; }
const validEntry = entry => entry && typeof entry === "object"
  && typeof entry.id === "string" && entry.id.startsWith("entry-")
  && typeof entry.title === "string" && entry.title.trim().length > 0 && entry.title.length <= 100
  && typeof entry.location === "string" && entry.location.trim().length > 0 && entry.location.length <= 80
  && typeof entry.story === "string" && entry.story.trim().length > 0 && entry.story.length <= 12000
  && /^\d{4}-\d{2}-\d{2}$/.test(entry.date) && !Number.isNaN(Date.parse(entry.date))
  && ["adventure", "interlude"].includes(entry.category);
let entries = Array.isArray(stored.entries) ? stored.entries.filter(validEntry) : [];
let bookmarks = new Set(Array.isArray(stored.bookmarks) ? stored.bookmarks.filter(id => typeof id === "string") : []);
let lastRead = typeof stored.lastRead === "string" ? stored.lastRead : null;
let view = "overview";
let filter = "all";
let query = "";
let toastTimer;
const $ = selector => document.querySelector(selector);
const make = (tag, className, text) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
};
const icon = name => {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  const use = document.createElementNS("http://www.w3.org/2000/svg", "use");
  use.setAttribute("href", `#i-${name}`);
  svg.setAttribute("aria-hidden", "true");
  svg.append(use);
  return svg;
};
const dateLabel = date => new Intl.DateTimeFormat("de-DE", { day: "2-digit", month: "short", year: "numeric", timeZone: "UTC" }).format(new Date(`${date}T12:00:00Z`));
const categoryLabel = category => category === "interlude" ? "Zwischenspiel" : "Abenteuer";
const allChapters = () => [
  ...entries.map((entry, index) => ({ ...entry, number: chapters.length + index + 1, image: entry.category === "interlude" ? "assets/tavern.svg" : "assets/forest.svg", excerpt: entry.story, story: entry.story.split(/\n\s*\n/) })).reverse(),
  ...chapters
];

function toast(message) {
  clearTimeout(toastTimer);
  $("#toast").textContent = message;
  $("#toast").classList.add("visible");
  toastTimer = setTimeout(() => $("#toast").classList.remove("visible"), 4000);
}

function persist() {
  try {
    localStorage.setItem(storageKey, JSON.stringify({ entries, bookmarks: [...bookmarks], lastRead }));
    return true;
  } catch {
    toast("Speichern nicht möglich. Bitte exportiere deine Einträge als Sicherung.");
    return false;
  }
}

function toggleBookmark(id) {
  if (bookmarks.has(id)) bookmarks.delete(id);
  else bookmarks.add(id);
  const saved = persist();
  renderChapters();
  if (saved) toast(bookmarks.has(id) ? "Zur Merkliste hinzugefügt." : "Aus der Merkliste entfernt.");
}

function renderChapters() {
  const all = allChapters();
  const result = all.filter(chapter =>
    (view !== "saved" || bookmarks.has(chapter.id))
    && (filter === "all" || chapter.category === filter)
    && (!query || `${chapter.title} ${chapter.location} ${chapter.excerpt} ${chapter.story.join(" ")}`.toLocaleLowerCase("de").includes(query))
  );
  const visible = view === "overview" && !query && filter === "all" ? result.slice(0, 3) : result;
  $("#chapter-grid").replaceChildren(...visible.map(chapter => {
    const card = make("article", "chapter-card");
    const cover = make("div", "card-cover");
    const image = make("img");
    image.src = chapter.image;
    image.alt = "";
    image.loading = "lazy";
    const bookmark = make("button", "bookmark");
    bookmark.type = "button";
    bookmark.setAttribute("aria-label", `${chapter.title}: ${bookmarks.has(chapter.id) ? "aus Merkliste entfernen" : "merken"}`);
    bookmark.setAttribute("aria-pressed", String(bookmarks.has(chapter.id)));
    bookmark.append(icon("bookmark"));
    bookmark.addEventListener("click", () => {
      toggleBookmark(chapter.id);
      const replacement = [...document.querySelectorAll(".bookmark")].find(button => button.dataset.id === chapter.id);
      if (replacement) replacement.focus({ preventScroll: true });
      else $("#search").focus({ preventScroll: true });
    });
    bookmark.dataset.id = chapter.id;
    cover.append(image, make("span", "chapter-number", `KAPITEL ${String(chapter.number).padStart(2, "0")}`), bookmark);
    const body = make("div", "card-body");
    const meta = make("div", "card-meta");
    const time = make("time", "", dateLabel(chapter.date));
    time.dateTime = chapter.date;
    meta.append(make("span", "card-category", categoryLabel(chapter.category)), make("span", "dot", "•"), time);
    const title = make("button", "card-title", chapter.title);
    title.addEventListener("click", () => openChapter(chapter.id));
    const footer = make("div", "card-footer");
    const location = make("span");
    location.append(icon("pin"), make("span", "", chapter.location));
    footer.append(location, icon("arrow"));
    body.append(meta, title, make("p", "card-excerpt", chapter.excerpt), footer);
    card.append(cover, body);
    return card;
  }));
  $("#results-count").textContent = result.length;
  $("#chapter-count").textContent = all.length;
  $("#stat-chapters").textContent = all.length;
  $("#saved-count").textContent = all.filter(chapter => bookmarks.has(chapter.id)).length;
  $("#empty-state").hidden = result.length > 0;
  $("#empty-description").textContent = view === "saved" && !query && filter === "all"
    ? "Merke dir ein Kapitel über das Lesezeichen auf seiner Karte."
    : "Versuche einen anderen Suchbegriff oder Filter.";
}

function renderHeroes() {
  $("#party-grid").replaceChildren(...heroes.map(hero => {
    const button = make("button", "party-card");
    const portrait = make("img", "portrait");
    portrait.src = `assets/portraits.svg#${hero.id}`;
    portrait.alt = "";
    portrait.style.borderColor = hero.color;
    const text = make("div");
    text.append(make("h3", "", hero.name), make("p", "", `${hero.race} · ${hero.role}`), make("span", "hero-level", `STUFE ${hero.level}`));
    button.append(portrait, text, icon("arrow"));
    button.addEventListener("click", () => openHero(hero));
    return button;
  }));
}

function setView(nextView) {
  view = nextView;
  filter = "all";
  query = "";
  $("#search").value = "";
  updateFilters();
  const titles = { overview: ["Die Chronik", "Von ersten Begegnungen und Abenteuern, die uns für immer verändern.", "Übersicht"], chapters: ["Unsere Kapitel", "Jede Entscheidung, jede Begegnung, jede unvergessliche Geschichte.", "Alle Kapitel"], heroes: ["Unsere Helden", "Vier ganz unterschiedliche Wege. Eine gemeinsame Geschichte.", "Unsere Helden"], saved: ["Deine Merkliste", "Geschichten, zu denen du immer wieder zurückkehren möchtest.", "Merkliste"] };
  const [title, description, breadcrumb] = titles[view];
  $("#page-title").textContent = title;
  $("#page-description").textContent = description;
  $("#breadcrumb-current").textContent = breadcrumb;
  $("#overview-feature").hidden = view !== "overview";
  $("#chapter-section").hidden = view === "heroes";
  $("#party-section").hidden = !["overview", "heroes"].includes(view);
  $("#all-chapters").hidden = view !== "overview";
  $("#all-heroes").hidden = view === "heroes";
  $("#chapters-heading").textContent = view === "overview" ? "Die letzten Kapitel" : view === "saved" ? "Deine gemerkten Kapitel" : "Alle Geschichten";
  $("main").classList.toggle("hero-view", view === "heroes");
  document.querySelectorAll(".nav-item").forEach(button => {
    const active = button.dataset.view === view;
    button.classList.toggle("active", active);
    if (active) button.setAttribute("aria-current", "page");
    else button.removeAttribute("aria-current");
  });
  renderChapters();
}

function updateFilters() {
  document.querySelectorAll(".tab").forEach(button => {
    button.classList.toggle("active", button.dataset.filter === filter);
    button.setAttribute("aria-pressed", String(button.dataset.filter === filter));
  });
}

function openChapter(id) {
  const all = allChapters();
  const chapter = all.find(item => item.id === id);
  if (!chapter) return;
  lastRead = id;
  persist();
  const image = make("img", "reader-cover");
  image.src = chapter.image;
  image.alt = chapter.category === "interlude" ? "Eine gemütliche Taverne bei Kerzenlicht" : "Landschaft an der Schwertküste";
  const body = make("div", "reader-body");
  const title = make("h2", "", chapter.title);
  title.id = "reader-title";
  const meta = make("div", "reader-meta");
  meta.append(make("span", "", dateLabel(chapter.date)), make("span", "", chapter.location), make("span", "", categoryLabel(chapter.category)));
  const story = make("div", "story-text");
  story.append(...chapter.story.map(paragraph => make("p", "", paragraph)));
  const bottom = make("div", "reader-bottom");
  const save = make("button", "button secondary");
  const updateSave = () => {
    save.replaceChildren(icon("bookmark"), document.createTextNode(bookmarks.has(id) ? "Gemerkt" : "Kapitel merken"));
    save.setAttribute("aria-pressed", String(bookmarks.has(id)));
  };
  updateSave();
  save.addEventListener("click", () => { toggleBookmark(id); updateSave(); });
  bottom.append(save);
  const next = all[all.findIndex(item => item.id === id) - 1];
  if (next) {
    const nextButton = make("button", "button parchment", `Weiter zu Kapitel ${next.number}`);
    nextButton.append(icon("arrow"));
    nextButton.addEventListener("click", () => openChapter(next.id));
    bottom.append(nextButton);
  } else {
    bottom.append(make("span", "storage-note", "Fortsetzung folgt. Das Abenteuer geht weiter."));
  }
  body.append(make("div", "eyebrow", `KAPITEL ${String(chapter.number).padStart(2, "0")}`), title, meta, story, bottom);
  $("#reader-content").replaceChildren(image, body);
  if (!$("#reader").open) $("#reader").showModal();
  $("#reader").scrollTop = 0;
}

function openHero(hero) {
  const body = make("div", "reader-body");
  const header = make("div", "character-header");
  const portrait = make("img", "portrait");
  portrait.src = `assets/portraits.svg#${hero.id}`;
  portrait.alt = `Porträt von ${hero.name}`;
  const info = make("div");
  const title = make("h2", "", hero.name);
  title.id = "reader-title";
  info.append(make("div", "eyebrow", `${hero.race} · ${hero.role}`), title, make("span", "hero-level", `STUFE ${hero.level} · DIE WÜRFELGEFÄHRTEN`));
  header.append(portrait, info);
  body.append(header, make("p", "character-detail", hero.description), make("p", "character-detail", hero.trait), make("blockquote", "character-quote", `„${hero.quote}“`));
  $("#reader-content").replaceChildren(body);
  $("#reader").showModal();
  $("#reader").scrollTop = 0;
}

